const {chromium}=require('../release/ui-check/node_modules/playwright');
const assert=require('node:assert/strict');
const mockWordstat=require('./wordstat-fixture.cjs');
const base=process.env.WORDSTAT_TEST_BASE||'http://127.0.0.1:8878';
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
  for(const entry of ['/','/hasl/','/email/',...(process.env.WORDSTAT_STANDALONE?['/OUTMAX.html']:[])]){
   const context=await browser.newContext({viewport:{width:1440,height:1000}});
   await context.request.post(base+'/login',{form:{login:'wiki-demo',password:'wiki-local-demo-only'}});
   await context.route('https://**',r=>r.abort());
   if(process.env.WORDSTAT_BLOCK_ASSET)await context.route(/\/editor-wordstat(?:-seo)?\.js(?:\?|$)/,r=>r.abort());
   const state=await mockWordstat(context);
   const page=await context.newPage(),errors=[];
   page.on('pageerror',error=>errors.push(error.message));
   await page.goto(base+entry,{waitUntil:'domcontentloaded'});
   await page.locator('#wordstat-open').waitFor();
   await page.waitForFunction(()=>document.querySelector('#wordstat-open img')?.naturalWidth>0);
   const email=entry.includes('email')||entry.includes('OUTMAX');
   if(!email)await page.waitForFunction(()=>articleBackupReady);
   await page.evaluate(email=>{
    const html='<p id="ws-control" style="color:#155fef">До <strong>текст 👟</strong> <a href="https://example.com/source">источник</a> [%name%]</p>';
    if(email){canvas.innerHTML=html;document.querySelector('#subject').value='Контрольная тема';document.querySelector('#preheader').value='Прехедер';resetEmailEditorHistory();}
    else{setBody(html);resetArticleEditorHistory();}
   },email);
   const snapshot=()=>page.evaluate(email=>JSON.stringify(email?[emailEditorSnapshot().body,document.querySelector('#subject').value,document.querySelector('#preheader').value,emailEditorHistoryIndex]:[articleEditorSnapshot().body,document.querySelector('#page-title').value,articleHistoryIndex]),email);
   const before=await snapshot();
   state.statusDelay=300;
   await page.locator('#wordstat-open').click();
   await page.locator('#ws-phrase').fill('кроссовки для бега');
   await page.locator('#ws-run:not(:disabled)').waitFor();
   state.statusDelay=0;
   assert.equal(state.calls.length,0,'opening must not query provider');
   await page.locator('#ws-phrase').fill('кроссовки для бега');
   await page.locator('#ws-run').click();
   await page.locator('#ws-results table').first().waitFor();
   assert.match(await page.locator('#ws-results').innerText(),/125.600/);
   await page.locator('#ws-tree').click();
   await page.locator('#ws-regions option[value="213"]').waitFor({state:'attached'});
   await page.locator('#ws-regions').selectOption('213');
   await page.locator('#ws-tree').click();
   await page.locator('#ws-status').filter({hasText:'Справочник загружен'}).waitFor();
   assert.equal(await page.locator('#ws-regions').inputValue(),'213','refresh keeps selected region');
   await page.locator('#ws-device').selectOption('DEVICE_PHONE');
   await page.locator('#ws-mode').selectOption('dynamics');
   await page.locator('#ws-from').fill('2026-01-01');await page.locator('#ws-to').fill('2026-03-31');
   await page.locator('#ws-run').click();await page.locator('.ws-chart').waitFor();
   assert.match(await page.locator('.ws-chart').textContent(),/2026-01-01/);
   assert.match(await page.locator('.ws-chart').textContent(),/2026-03-01/);
   assert.equal(await page.locator('.ws-chart line').count(),5,'chart has integer count scale');
   assert.deepEqual(state.calls.at(-1).regions,['213']);
   assert.equal(state.calls.at(-1).device,'DEVICE_PHONE');
   await page.locator('#ws-mode').selectOption('regions');
   assert.equal(await page.locator('#ws-geography').isVisible(),false);
   await page.locator('#ws-run').click();
   await page.getByRole('cell',{name:'Москва',exact:true}).waitFor();
   for(const width of [390,320,800,1440]){
    await page.setViewportSize({width,height:900});
    assert.ok(await page.locator('#wordstat-dialog').evaluate(n=>n.scrollWidth<=n.clientWidth+1),`dialog overflow ${width}`);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
   }
   state.delay=700;
   await page.locator('#ws-run').click();
   await page.locator('#ws-phrase').fill('новые условия');
   await page.waitForTimeout(900);
   assert.equal(await page.locator('#ws-results table').count(),0,'stale response discarded');
   state.delay=0;state.error=true;
   await page.locator('#ws-run').click();
   await page.locator('#ws-status').filter({hasText:'Лимит'}).waitFor();
   assert.equal(await page.locator('#ws-run').isEnabled(),true);
   state.error=false;
   await page.locator('#ws-settings summary').click();
   const queries=state.calls.length;
   state.configureError=true;
   await page.locator('#ws-key').fill('demo-key-never-real');
   await page.locator('#ws-save').click();
   await page.locator('#ws-settings-status').filter({hasText:'Проверьте API-ключ'}).waitFor();
   await page.locator('#ws-save:not(:disabled)').waitFor();
   assert.equal(await page.locator('#ws-run').isEnabled(),true,'failed configuration reconciles previous connection');
   assert.equal(state.calls.length,queries,'configuration does not query provider');
   assert.equal(await page.locator('#ws-key').inputValue(),'');
   state.configureError='network';
   await page.locator('#ws-save').click();
   await page.locator('#ws-settings-status').filter({hasText:'Не удалось связаться'}).waitFor();
   await page.locator('#ws-save:not(:disabled)').waitFor();
   assert.equal(await page.locator('#ws-run').isEnabled(),true,'network failure reconciles configuration without resubmission');
   assert.equal(state.calls.length,queries);
   state.configureError=false;
   await page.locator('#ws-save').click();
   await page.locator('#ws-settings-status').filter({hasText:'Настройки сохранены'}).waitFor();
   assert.equal(state.configurations.at(-1).apiKey,'','empty key preserves configured key');
   await page.locator('#ws-clear').click();
   await page.locator('#ws-status').filter({hasText:'не подключён'}).waitFor();
   assert.equal(await page.locator('#ws-run').isDisabled(),true);
   state.available=true;
   await page.keyboard.press('Escape');
   await page.locator('#wordstat-open').click();
   await page.locator('#ws-run:not(:disabled)').waitFor();
   // A late save must not unlock settings managed by a newly read server environment.
   state.configureDelay=500;
   await page.locator('#ws-save').click();
   await page.locator('#ws-key:disabled').waitFor();
   assert.equal(await page.locator('#ws-run').isDisabled(),true);
   await page.keyboard.press('Escape');
   state.managed=true;
   await page.locator('#wordstat-open').click();
   await page.locator('#ws-settings-status').filter({hasText:'окружением сервера'}).waitFor();
   await state.configureFinished;
   await page.locator('#ws-run:not(:disabled)').waitFor();
   assert.equal(await page.locator('#ws-save').isDisabled(),true,'late save cannot enable managed configuration');
   assert.equal(await page.locator('#ws-key').isDisabled(),true);
   state.managed=false;state.configureDelay=0;
   await page.keyboard.press('Escape');
   await page.locator('#wordstat-open').click();
   await page.locator('#ws-key:not(:disabled)').waitFor();
   await page.locator('#ws-key').fill('demo-key-never-real');
   await page.keyboard.press('Escape');
   assert.equal(await page.locator('#ws-key').inputValue(),'');
   assert.equal(await snapshot(),before,'research must preserve HTML, fields and undo');
   assert.equal(await page.evaluate(()=>document.activeElement.id),'wordstat-open');
   state.canConfigure=false;state.available=false;
   const commandPrefix=email?'email':'article';
   await page.locator(`#${commandPrefix}-commands-open`).click();
   await page.locator(`#${commandPrefix}-command-search`).fill('Wordstat');
   await page.locator(`#${commandPrefix}-command-results`).getByRole('button',{name:'Яндекс Wordstat: фразы, динамика и регионы',exact:true}).click();
   await page.locator('#wordstat-dialog[open]').waitFor();
   await page.locator('#ws-status').filter({hasText:'не подключён'}).waitFor();
   assert.equal(await page.locator('#ws-settings').isVisible(),false);
   assert.equal(await page.locator('#ws-phrase').evaluate(node=>node===document.activeElement),true,'command focuses phrase');
   assert.equal(await page.locator('#ws-run').isDisabled(),true);
   await page.keyboard.press('Escape');
   assert.deepEqual(errors,[]);
   await context.close();console.log('PASS Wordstat '+entry+': reports, filters, stale/error, mobile, focus, command, unchanged document/history');
  }
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
